// 看玩家電腦上的真實時間說話
function muonTimeLine() {
    const now = new Date();
    const h = now.getHours();
    const time = String(h).padStart(2, '0') + ':' + String(now.getMinutes()).padStart(2, '0');
    if (h < 6)  return `現在時間 ${time}。這個時間，以前也有人醒著。`;
    if (h < 12) return `現在時間 ${time}。早上了。海底，沒有早上。`;
    if (h < 18) return `現在時間 ${time}。補給船，以前是這個時間來。`;
    return `現在時間 ${time}。居住區的燈，我還留著。`;
}
